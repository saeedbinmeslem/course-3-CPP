#include <iostream>
using namespace std;

int main()
{
    short A;
    short B;

    cout << "Please enter the first Number A? " << endl;
    cin >> A;

    cout << "Please enter the first Number B? " << endl;
    cin >> B;
    cout << endl;
    cout << A << " + " << B << " = " << A + B << endl;
    cout << A << " - " << B << " = " << A - B << endl;
    cout << A << " * " << B << " = " << A * B << endl;
    cout << A << " / " << B << " = " << A / B << endl;
    cout << A << " % " << B << " = " << A % B << endl;

}